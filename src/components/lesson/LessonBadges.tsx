// Where a lesson came from, at a glance: seed library or generated, review status, simplified.

import type { Lesson } from '@/lib/music/types';
import { formatDate } from '@/lib/format';
import { Icon } from '@/components/ui/Icon';
import ui from '@/components/ui/ui.module.css';

export function OriginBadge({ origin }: { origin: Lesson['origin'] }) {
  return origin === 'seed' ? (
    <span className={`${ui.badge} ${ui.badgeSeed}`} title="Part of the seed library that ships with the app">
      <Icon name="book" size={14} />
      Seed library
    </span>
  ) : (
    <span className={`${ui.badge} ${ui.badgeGenerated}`} title="Written by the lesson generator and checked by the validator before publishing">
      <Icon name="sparkle" size={14} />
      Generated
    </span>
  );
}

export function LessonBadges({ lesson, review }: { lesson: Lesson; review?: boolean }) {
  return (
    <div className={ui.badges}>
      <OriginBadge origin={lesson.origin} />
      {lesson.simplified ? (
        <span className={ui.badge} title={lesson.simplificationNote}>
          Simplified
        </span>
      ) : null}
      {lesson.kind === 'lick' && lesson.difficulty ? (
        <span className={ui.badge} aria-label={`Difficulty ${lesson.difficulty} of 5`}>
          <span aria-hidden="true">{'●'.repeat(lesson.difficulty) + '○'.repeat(5 - lesson.difficulty)}</span>
        </span>
      ) : null}
      {review ? <span className={`${ui.badge} ${ui.badgeReview}`}>Review day</span> : null}
    </div>
  );
}

/** One sentence on how the lesson was checked, for the credits at the bottom of a lesson. */
export function Provenance({ lesson }: { lesson: Lesson }) {
  if (lesson.origin === 'generated' && lesson.generator) {
    return (
      <p>
        Generated by {lesson.generator.service} ({lesson.generator.version}) on {formatDate(lesson.generator.generatedAt)}. It passed the same
        validator as the seed library (rhythm, string and fret pitches, fingering, analysis, transposition and an alphaTab round trip) before it
        was published, but no person has played through it yet. The recordings listed are listening suggestions for the style, chosen by a
        person; the notes do not come from them.
      </p>
    );
  }
  if (lesson.review?.status === 'awaiting-play-through') {
    return (
      <p>
        Seed library lesson, checked on {formatDate(lesson.review.reviewedOn)} by {lesson.review.reviewedBy}. Every note passed the validator
        (rhythm, string and fret pitches, fingering, analysis, transposition and an alphaTab round trip), but nobody has played it through on
        a guitar yet.
      </p>
    );
  }
  if (lesson.review) {
    return (
      <p>
        Seed library lesson, reviewed on {formatDate(lesson.review.reviewedOn)} by {lesson.review.reviewedBy}. Every note was checked by the
        validator (rhythm, string and fret pitches, fingering, analysis, transposition and an alphaTab round trip).
      </p>
    );
  }
  return null;
}
